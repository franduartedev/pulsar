#!/usr/bin/env python3
"""Content and determinism checks for the authored Core Sounds pack."""
from __future__ import annotations

import hashlib
import importlib.util
import io
import math
import pathlib
import random
import struct
import wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("generator", ROOT / "tools" / "generate_core_sounds.py")
assert spec and spec.loader
generator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generator)


def wav_bytes(samples: list[float]) -> bytes:
    output = io.BytesIO()
    with wave.open(output, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(generator.RATE)
        handle.writeframes(b"".join(struct.pack("<h", round(x * 32767)) for x in samples))
    return output.getvalue()


def main() -> None:
    for index, (sound_id, _name, _category, seconds, kind) in enumerate(generator.SOUNDS):
        first = wav_bytes(generator.render(kind, seconds, random.Random(generator.SEED + index)))
        second = wav_bytes(generator.render(kind, seconds, random.Random(generator.SEED + index)))
        assert hashlib.sha256(first).digest() == hashlib.sha256(second).digest(), sound_id
        path = ROOT / "assets" / "sounds" / f"{sound_id}.wav"
        with wave.open(str(path), "rb") as handle:
            assert handle.getnchannels() == 1, sound_id
            assert handle.getframerate() == 48000, sound_id
            assert handle.getnframes() == round(seconds * 48000), sound_id
            samples = list(struct.unpack("<%dh" % handle.getnframes(), handle.readframes(handle.getnframes())))
        normalized = [sample / 32767.0 for sample in samples]
        assert normalized and all(math.isfinite(sample) for sample in normalized), sound_id
        peak = max(abs(sample) for sample in normalized)
        rms = math.sqrt(sum(sample * sample for sample in normalized) / len(normalized))
        assert peak > 1e-4, (sound_id, "insignificant peak")
        assert rms > 1e-5, (sound_id, "insignificant rms")
        assert peak <= 0.9501, (sound_id, "clipping")
        assert first == path.read_bytes(), (sound_id, "generated bytes differ")


if __name__ == "__main__":
    main()
